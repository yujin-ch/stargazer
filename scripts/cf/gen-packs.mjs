// Cloudflare Pages build step: bundle packs/*.json into the night function (Pages Functions can't read files).
// Writes cf/packs.gen.js (gitignored). Run by `npm run build:cf`.
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";

const files = (await readdir("packs")).filter((f) => /^\d{4}-\d{2}-\d{2}\.json$/.test(f)).sort();
const packs = {};
for (const f of files) packs[f.slice(0, 10)] = JSON.stringify(JSON.parse(await readFile(`packs/${f}`, "utf8")));
await mkdir("cf", { recursive: true });
await writeFile("cf/packs.gen.js", `// generated by scripts/cf/gen-packs.mjs, do not edit\nexport default ${JSON.stringify(packs)};\n`);
console.log(`cf/packs.gen.js: ${files.length} nights`);
